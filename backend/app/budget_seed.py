def build_budget_seed(service: BudgetService) -> dict[str, list[dict[str, Any]]]:
    """通过服务层导入种子数据并完成首轮核算，返回各表初始行。"""
    for item in BUDGET_ITEMS:
        entry, message = service.create_item(dict(item))
        if entry is None:  # pragma: no cover - 种子数据本身应合法
            raise RuntimeError(f"预算种子条目非法：{message}")

    service.import_expenses({"批次号": "SEED-EXPENSE-001", "费用明细": EXPENSE_LINES})
    # 场景六：同号重复凭证重复导入，指纹去重后只记一次。
    service.import_expenses({
        "批次号": "SEED-EXPENSE-002",
        "费用明细": [line for line in EXPENSE_LINES if line["凭证号"] == "JV-202610-001"],
    })
    service.import_reversals({"批次号": "SEED-REVERSAL-001", "冲销记录": REVERSAL_LINES})

    basis = service.run_accounting(trigger="核算", remark="种子数据首轮核算")

    from app.store import store

    from app.services import budget as budget_module

    tables: dict[str, list[dict[str, Any]]] = {}
    for name in budget_module.ALL_TABLES:
        tables[name] = store.rows(name)
    tables["_首轮依据"] = [basis]  # 仅用于自检，不进仓库
    return tables
